SELECT ID, EMAIL, FIRST_NAME, LAST_NAME FROM DEVELOPERS WHERE CONV(SKILL_CODE >> (
    SELECT LENGTH(CAST(CONV(CODE,10,2) as CHAR))-1 FROM SKILLCODES WHERE NAME = "Python"
),10,2) LIKE "%1" OR 
CONV(SKILL_CODE >> (
    SELECT LENGTH(CAST(CONV(CODE,10,2) as CHAR))-1 FROM SKILLCODES WHERE NAME = "C#"
),10,2) LIKE "%1" ORDER BY ID;
SELECT ID, GENOTYPE, (
    SELECT GENOTYPE FROM ECOLI_DATA B WHERE B.ID = A.PARENT_ID
) AS PARENT_GENOTYPE FROM ECOLI_DATA A WHERE A.GENOTYPE & (
    SELECT GENOTYPE FROM ECOLI_DATA B WHERE B.ID = A.PARENT_ID
) = (
    SELECT GENOTYPE FROM ECOLI_DATA B WHERE B.ID = A.PARENT_ID
)
ORDER BY ID;
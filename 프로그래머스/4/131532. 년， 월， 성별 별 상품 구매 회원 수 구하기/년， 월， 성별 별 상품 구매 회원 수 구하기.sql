SELECT YEAR(SALES_DATE), MONTH(SALES_DATE), GENDER, COUNT(*) FROM (
    SELECT YEAR(SALES_DATE), MONTH(SALES_DATE), GENDER, A.USER_ID,SALES_DATE FROM ONLINE_SALE A JOIN USER_INFO B ON A.USER_ID = B.USER_ID GROUP BY YEAR(SALES_DATE), MONTH(SALES_DATE), GENDER, A.USER_ID
) AS A WHERE GENDER IS NOT NULL GROUP BY YEAR(SALES_DATE), MONTH(SALES_DATE), GENDER 
ORDER BY YEAR(SALES_DATE), MONTH(SALES_DATE), GENDER;
SELECT HISTORY_ID, (DATEDIFF(END_DATE,START_DATE)+1) * (DAILY_FEE *(1 - (IF(DATEDIFF(END_DATE,START_DATE)+1  >= 90, (
    SELECT DISCOUNT_RATE FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN 
    WHERE DURATION_TYPE LIKE "90%" AND CAR_TYPE = "트럭"
),IF(DATEDIFF(END_DATE,START_DATE)+1 >= 30,(
    SELECT DISCOUNT_RATE FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN 
    WHERE DURATION_TYPE LIKE "30%" AND CAR_TYPE = "트럭"
),IF(DATEDIFF(END_DATE,START_DATE)+1 >= 7,(
    SELECT DISCOUNT_RATE FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN 
    WHERE DURATION_TYPE LIKE "7%" AND CAR_TYPE = "트럭"
),0)))*0.01))) AS FEE FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY B 
JOIN CAR_RENTAL_COMPANY_CAR A ON A.CAR_ID = B.CAR_ID WHERE CAR_TYPE = "트럭" ORDER BY FEE DESC,HISTORY_ID DESC;


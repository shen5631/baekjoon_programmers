SELECT E.EMP_NO, E.EMP_NAME, 
IF(AVG(G.SCORE)>=96, "S", IF(AVG(G.SCORE) >= 90, "A", IF(AVG(G.SCORE) >= 80, "B","C"))) AS GRADE,
IF(AVG(G.SCORE) >= 96, E.SAL*0.2, IF(AVG(G.SCORE) >= 90, E.SAL * 0.15,IF(AVG(G.SCORE) >= 80, E.SAL*0.1, 0))) AS BONUS
FROM HR_GRADE G JOIN HR_EMPLOYEES E ON E.EMP_NO = G.EMP_NO
GROUP BY G.EMP_NO
ORDER BY EMP_NO;